-- ============================================================
-- 苍穹外卖数据库索引优化脚本
-- 作用：为高频查询字段补充索引，避免全表扫描，提升查询性能
--
-- 说明：
-- 1. 本脚本是「增量优化」，不改变原有表结构，只新增索引；
-- 2. 所有索引都基于 MyBatis 里真实存在的高频 WHERE 条件推导；
-- 3. 可在已部署的数据库上直接执行（需确认索引名不冲突）。
-- ============================================================

-- ------------------------------------------------------------
-- 1. dish 表：按分类查菜品是 C 端最高频查询
--    原索引：仅主键 + name 唯一索引，category_id 无索引 → 全表扫描
-- ------------------------------------------------------------
ALTER TABLE `dish` ADD INDEX `idx_dish_category_id` (`category_id`);

-- ------------------------------------------------------------
-- 2. dish_flavor 表：按菜品查口味
--    原索引：仅主键，dish_id 无索引
-- ------------------------------------------------------------
ALTER TABLE `dish_flavor` ADD INDEX `idx_dish_flavor_dish_id` (`dish_id`);

-- ------------------------------------------------------------
-- 3. order_detail 表：按订单查明细
--    原索引：仅主键，order_id 无索引
-- ------------------------------------------------------------
ALTER TABLE `order_detail` ADD INDEX `idx_order_detail_order_id` (`order_id`);

-- ------------------------------------------------------------
-- 4. orders 表：订单表，查询维度最多，最关键
--    原索引：仅主键
--    - status：定时任务按状态扫描（超时订单、状态统计）
--    - user_id：用户查自己的历史订单
--    - number：按订单号精确查询（支付回调、来单提醒）
-- ------------------------------------------------------------
ALTER TABLE `orders` ADD INDEX `idx_orders_status` (`status`);
ALTER TABLE `orders` ADD INDEX `idx_orders_user_id` (`user_id`);
ALTER TABLE `orders` ADD INDEX `idx_orders_number` (`number`);

-- ------------------------------------------------------------
-- 5. setmeal 表：按分类查套餐（C 端浏览）
--    原索引：主键 + name 唯一索引，category_id 无索引
-- ------------------------------------------------------------
ALTER TABLE `setmeal` ADD INDEX `idx_setmeal_category_id` (`category_id`);

-- ------------------------------------------------------------
-- 6. setmeal_dish 表：按套餐查菜品
--    原索引：仅主键，setmeal_id 无索引
-- ------------------------------------------------------------
ALTER TABLE `setmeal_dish` ADD INDEX `idx_setmeal_dish_setmeal_id` (`setmeal_id`);

-- ------------------------------------------------------------
-- 7. shopping_cart 表：按用户查购物车
--    原索引：仅主键，user_id 无索引
-- ------------------------------------------------------------
ALTER TABLE `shopping_cart` ADD INDEX `idx_shopping_cart_user_id` (`user_id`);

-- ------------------------------------------------------------
-- 8. address_book 表：按用户查地址
--    原索引：仅主键，user_id 无索引
-- ------------------------------------------------------------
ALTER TABLE `address_book` ADD INDEX `idx_address_book_user_id` (`user_id`);

-- ------------------------------------------------------------
-- 9. user 表：按 openid 查询（微信登录）
--    原索引：仅主键，openid 无索引 → 每次登录全表扫描
-- ------------------------------------------------------------
ALTER TABLE `user` ADD INDEX `idx_user_openid` (`openid`);

-- ------------------------------------------------------------
-- 10. category 表：按状态查分类（启用的分类）
--     原索引：主键 + name 唯一索引，status 无索引
-- ------------------------------------------------------------
ALTER TABLE `category` ADD INDEX `idx_category_status` (`status`);

-- ============================================================
-- 验证索引是否生效（可选）
-- EXPLAIN 查看执行计划，重点看 type 是否从 ALL（全表扫描）变为 ref/const
-- ============================================================
-- EXPLAIN SELECT * FROM dish WHERE category_id = 11;
-- EXPLAIN SELECT * FROM orders WHERE user_id = 1;
-- EXPLAIN SELECT * FROM order_detail WHERE order_id = 1;

-- ============================================================
-- 设计说明（为什么这样加索引）
-- ============================================================
-- 1. 索引不是越多越好：每个索引都占用磁盘空间、拖慢写操作（INSERT/UPDATE/DELETE 都要维护索引），
--    所以只给「高频查询字段」加，不给「低频/高基数区分度低」的字段加；
-- 2. 遵循「最左前缀」原则：本脚本大多是单列等值查询，单列索引即可；
--    若未来出现「status + order_time」组合查询，可建联合索引 (status, order_time)；
-- 3. 区分度（选择性）：openid、number 这类接近唯一的字段，索引区分度高、效果最好；
--    status 只有 0/1 几种取值、区分度低，但作为定时任务扫描和统计的过滤条件，依然有价值；
-- 4. 唯一索引 vs 普通索引：name/username 用唯一索引（业务上不允许重名），
--    user_id/category_id 等用普通索引（允许重复）。
